#!/usr/bin/env python3
"""Generate real offscreen screenshots of the Image Scrub GUI.

Runs the actual PySide6 MainWindow with the Qt offscreen platform, feeds it a
genuine sample set of images with embedded provenance metadata, then captures
two frames: the clean (ready) state and the completed-run state.

Usage:
    QT_QPA_PLATFORM=offscreen python3 scripts/make_screenshots.py
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from PIL import Image, PngImagePlugin
from PySide6.QtWidgets import QApplication

from desktop_gui import MainWindow
from image_scrub.pipeline import process
from image_scrub.plugins import load_plugins

SCREENSHOTS = Path(__file__).resolve().parent.parent / "docs" / "screenshots"


def make_sample_images(root: Path) -> None:
    """Create a few images that carry real provenance markers."""
    root.mkdir(parents=True, exist_ok=True)
    files = [
        ("generated-portrait.jpg", "JPEG", (120, 80, 40)),
        ("hero-banner.png", "PNG", (30, 30, 70, 255)),
        ("product-shot.jpg", "JPEG", (200, 180, 150)),
        ("album-cover.png", "PNG", (10, 90, 120, 255)),
    ]
    for name, fmt, color in files:
        p = root / name
        mode = "RGB" if fmt == "JPEG" else "RGBA"
        img = Image.new(mode, (640, 480), color)
        if fmt == "JPEG":
            exif = Image.Exif()
            exif[0x013B] = "Generated with a text-to-image model"   # Artist
            exif[0x010E] = "AI image generator v2.1"                # ImageDescription
            exif[0x8298] = "Copyright — generated content"          # Copyright
            img.save(p, "JPEG", exif=exif, quality=95)
        else:
            meta = PngImagePlugin.PngInfo()
            meta.add_text("Software", "AI image generator v2.1")
            meta.add_text("Source", "generated by latent diffusion model")
            img.save(p, pnginfo=meta)


def grab(window: MainWindow, path: Path) -> None:
    window.show()
    QApplication.processEvents()
    QApplication.processEvents()
    window.grab().save(str(path))


def main() -> int:
    app = QApplication(sys.argv)
    SCREENSHOTS.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as td:
        src = Path(td) / "input"
        out = Path(td) / "scrubbed"
        make_sample_images(src)

        w = MainWindow()
        # Show clean, representative paths in the pickers (actual files are
        # processed from the temp dir above; only filenames appear in results).
        w.src_edit.setText("~/Pictures/originals")
        w.out_edit.setText("~/Pictures/scrubbed")
        w.level.setCurrentIndex(1)

        # Clean state shot
        grab(w, SCREENSHOTS / "gui-main.png")

        # Run the real pipeline and feed the authentic results into the table
        detectors = load_plugins(specs=["metadata"])
        results = process(
            str(src), str(out), level=1, detectors=detectors, progress=None
        )
        w.on_done(results)
        w.progress.setVisible(True)
        w.progress.setRange(0, len(results))
        w.progress.setValue(len(results))

        # Select a row with an actual removal so the provenance detail pane
        # (before/after + diff) demonstrates its value in the screenshot.
        sel = 0
        for i, rr in enumerate(results):
            if rr.status == "ok" and rr.provenance_diff.get("removed"):
                sel = i
                break
        w.table.selectRow(sel)
        QApplication.processEvents()

        grab(w, SCREENSHOTS / "gui-results.png")

    print(f"Wrote {SCREENSHOTS / 'gui-main.png'}")
    print(f"Wrote {SCREENSHOTS / 'gui-results.png'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
